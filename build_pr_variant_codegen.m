function build_pr_variant_codegen(variant, outputDir)
% Build one of the experimental PR variants for MCU testing.
% Examples:
%   build_pr_variant_codegen("pr_a", fullfile(tempdir,"ppg_pr_a"))
%   build_pr_variant_codegen("pr_b", fullfile(tempdir,"ppg_pr_b"))
%   build_pr_variant_codegen("pr_c", fullfile(tempdir,"ppg_pr_c"))

if nargin < 1 || isempty(variant)
    variant = "pr_a";
end
if nargin < 2 || isempty(outputDir)
    outputDir = fullfile(tempdir, "ppg_" + string(variant));
end

variant = string(variant);
assert(ismember(variant, ["pr_a","pr_b","pr_c"]), ...
    'variant必须为pr_a、pr_b或pr_c。');

rootDir = fileparts(mfilename('fullpath'));
variantDir = fullfile(rootDir, 'variants', char(variant));
assert(isfolder(variantDir), '找不到算法目录：%s', variantDir);

addpath(rootDir, '-end');
addpath(variantDir, '-begin');
restoreVariantPath = onCleanup(@()rmpath(variantDir));
previousFolder = pwd;
restoreFolder = onCleanup(@()cd(previousFolder));
cd(variantDir); % MATLAB 当前目录优先；确保 codegen 选中变体目录中的 ppg_process
clear ppg_process r_pr_calculation

build_ppg_codegen( ...
    'OutputDir', outputDir, ...
    'MultiInstanceCode', false, ...
    'EnableOpenMP', false, ...
    'EnableAutoParallelization', false, ...
    'UseBuiltInCTypes', true, ...
    'EnableDynamicMemoryAllocation', true, ...
    'DynamicMemoryAllocationThreshold', 1280, ...
    'DynamicMemoryAllocationForFixedSizeArrays', false, ...
    'GenCodeOnly', true, ...
    'GenerateMakefile', false, ...
    'GenerateExampleMain', 'GenerateCodeOnly', ...
    'ProdHWDeviceType', 'ARM Compatible->ARM Cortex-M', ...
    'GenerateReport', false);
end
